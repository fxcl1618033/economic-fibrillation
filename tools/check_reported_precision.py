"""
After tools/rerun_asrun.py: does any number we *report* change, at the precision we report it?

    python3 tools/check_reported_precision.py                    # as-run outputs: writes build/asrun/PRECISION.md
    python3 tools/check_reported_precision.py --data build/data  # the src build (GMD read as float64):
                                                                 # writes build/data/PRECISION.md

Three checks:
  1. Every compared number: how many differ, the largest difference overall and the largest outside phase
     angles, and whether any p-value changed.
  2. Registry rows that come from files built on the Global Macro Database (G1–G8), plus D10 and H4,
     recomputed from the stored and the rerun files and printed at the precision the registry uses.
  3. The atlas text: atlas.tex rendered by atlas/build_tex.py from the stored files and from the rerun files.
     Every number printed in the atlas passes through this step, so identical text means no atlas value changed.
"""
import json, os, re, shutil, subprocess, sys, tempfile
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
import numpy as np, pandas as pd
from ef import repro
from ef.repro import compare


class NonPhase(repro.Tally):
    def number(self, path, field, new, old, is_p=False):
        if "phase" not in field.lower(): super().number(path, field, new, old, is_p)


import argparse
ap = argparse.ArgumentParser(); ap.add_argument("--data", help="a src data build (ef.data.build) to check instead of the as-run GMD outputs")
args = ap.parse_args()
OUT = "build/asrun"
if not os.path.exists(f"{OUT}/REPORT.md"): sys.exit("run tools/rerun_asrun.py first")
GMD_P26 = f"{args.data}/panel26_results.json" if args.data else f"{OUT}/internal/panel26_results.json"
GMD_ATLAS = f"{args.data}/atlas" if args.data else f"{OUT}/atlas"
DEST = args.data or OUT
FILES = [] if args.data else [(f"{OUT}/{n}", f"paper1/results/{n}") for n in sorted(os.listdir("paper1/results"))
                               if n.endswith(".json") and n != "panel26_results.json" and os.path.exists(f"{OUT}/{n}")]
if not args.data:
    FILES += [(f"{OUT}/hilbert_output.csv", "paper1/data/hilbert_output.csv"), (f"{OUT}/surrogate_results.csv", "paper1/results/surrogate_results.csv")]
FILES += [(GMD_P26, "paper1/results/panel26_results.json")]
FILES += [(f"{GMD_ATLAS}/{f}", f"atlas/{f}") for f in ("panel.csv", "global.csv", "meta.json", "stats.json", "sync.json")]

out = ["# Reported-precision check", "", f"Generated by `tools/check_reported_precision.py` from `{DEST}/` (this machine) against the stored files."
       + (" The GMD-built files come from the src build, which reads GMD as float64; Paper 1's rows come from `build/asrun/`." if args.data else ""), "",
       "## 1. Every compared number", "",
       "Largest difference is absolute; relative is the largest |difference| / max(1, |stored value|), which is what matters for levels such as real consumption in local currency.", "",
       "| File | Numbers | Differ | Largest difference | Largest relative | Largest outside phase angles | p-values changed |", "|---|---|---|---|---|---|---|"]
tot = dict(n=0, d=0, p=0); big = (0, ""); bignp = (0, ""); bigrel = (0, "")
for new, old in FILES:
    t = compare(new, old)
    tnp = NonPhase()   # the same comparison with phase angles left out
    if old.endswith(".json"): repro._walk_json(json.load(open(new)), json.load(open(old)), tnp)
    else:
        A, B = pd.read_csv(new), pd.read_csv(old)
        key = [c for c in ("iso", "year") if c in B.columns]
        lab = (B[key].astype(str).agg(" ".join, axis=1) if key else B.index.astype(str)).tolist()
        for c in B.columns:
            if pd.api.types.is_numeric_dtype(B[c]) and not pd.api.types.is_bool_dtype(B[c]):
                for i, (x, y) in enumerate(zip(A[c].astype(float), B[c].astype(float))): tnp.number(f"{c}[{lab[i]}]", c, x, y)
    tot["n"] += t.n; tot["d"] += t.n_diff; tot["p"] += len(t.p_changes)
    if t.max_abs > big[0]: big = (t.max_abs, f"{old}: {t.max_abs_at}")
    if tnp.max_abs > bignp[0]: bignp = (tnp.max_abs, f"{old}: {tnp.max_abs_at}")
    if t.max_scaled > bigrel[0]: bigrel = (t.max_scaled, f"{old}: {t.max_scaled_at}")
    fmt = lambda v, w: "0" if v == 0 else f"{v:.2g} ({w})"
    out.append(f"| `{old}` | {t.n} | {t.n_diff} | {fmt(t.max_abs, t.max_abs_at)} | {fmt(t.max_scaled, t.max_scaled_at)} | {fmt(tnp.max_abs, tnp.max_abs_at)} | {len(t.p_changes)} |")
out += ["", f"**All files:** {tot['n']:,} numbers compared, {tot['d']:,} differ. Largest difference {big[0]:.2g} ({big[1]}); "
        f"largest relative {bigrel[0]:.2g} ({bigrel[1]}); largest outside phase angles {bignp[0]:.2g} ({bignp[1]}). p-values changed: {tot['p']}.", ""]

# ---- 2. registry rows at reported precision
J = lambda p: json.load(open(p))
S_old, S_new = J("atlas/sync.json"), J(f"{GMD_ATLAS}/sync.json")
P_old, P_new = J("paper1/results/panel26_results.json")["res"], J(GMD_P26)["res"]
T_old, T_new = J("atlas/stats.json"), J(f"{GMD_ATLAS}/stats.json")
G_old, G_new = pd.read_csv("atlas/global.csv").set_index("year"), pd.read_csv(f"{GMD_ATLAS}/global.csv").set_index("year")
U_old, U_new = pd.read_csv("paper1/results/surrogate_results.csv"), pd.read_csv(f"{OUT}/surrogate_results.csv")
I26 = [o[0] for o in J("atlas/meta.json")["order"]]
sg = lambda x: f"{x:+.3f}".replace("-", "−")
def rows(S, P, T, G, U, ident):
    t = S["tests"]; r = {}
    r["G1 short-rate sync, lead-2"] = f"{sg(t['strate']['lead2'][0])} (p {t['strate']['lead2'][1]:.3f})"
    r["G2 investment sync, lead-2"] = f"{sg(t['inv']['lead2'][0])} (p {t['inv']['lead2'][1]:.3f})"
    r["G3 real GDP sync, lead-1 / after-2"] = f"{sg(t['GDP']['lead1'][0])} / {sg(t['GDP']['after2'][0])} (p {t['GDP']['lead1'][1]:.3f} / {t['GDP']['after2'][1]:.3f})"
    mr = [P[c]["mean_r"] for c in P]; nr = [P[c]["null_r"] for c in P]; ps = sorted({round(P[c]["p_sync"], 4) for c in P})
    r["G4 channel mean r range; null range; p"] = f"{min(mr):.2f}–{max(mr):.2f}; {min(nr):.2f}–{max(nr):.2f}; {ps}"
    r["G5 pairwise corr pre→post 1990: GDP, exports, imports, balance"] = ", ".join(f"{P[c]['paircorr_pre90']:.2f}→{P[c]['paircorr_post90']:.2f}" for c in ("GDP", "exports", "imports", "balance"))
    r["G7 economies contracting 2020 / 2009 / 1975, 1982, 1991"] = f"{int(G.n_contracting[2020])} / {int(G.n_contracting[2009])} / {', '.join(str(int(G.n_contracting[y])) for y in (1975, 1982, 1991))}"
    r["G8 average coupling to the rest, 1970–89 vs 1990–2022"] = f"{np.mean([T[i]['coup_7089'] for i in I26]):.2f} vs {np.mean([T[i]['coup_9022'] for i in I26]):.2f}"
    r["H4 first-pass surrogate test (whole table, 2 decimals)"] = U.round(2).to_csv(index=False)
    r["D10 fibrillation identity, max error (1 significant figure)"] = f"{ident:.0e}"
    return r
ident_old = J("paper1/results/structure_results.json")["identity_err"]
m = re.search(r"max\|err\| = ([0-9.e+-]+)", open(f"{OUT}/log_structure_tests.txt").read()); ident_new = float(m.group(1))
ro, rn = rows(S_old, P_old, T_old, G_old, U_old, ident_old), rows(S_new, P_new, T_new, G_new, U_new, ident_new)
out += ["## 2. Registry rows built on GMD data, at the precision the registry reports", "",
        "Rows A1–F5 come from files that are EXACT above, so they cannot change. G6 is the `usjp` printout, compared line by line in REPORT.md.", "",
        "| Row | Stored | Rerun | Same? |", "|---|---|---|---|"]
changed = []
for k in ro:
    same = ro[k] == rn[k]
    if not same: changed.append(k)
    show = (lambda v: "table" if k.startswith("H4") else v)
    out.append(f"| {k} | {show(ro[k])} | {show(rn[k])} | {'yes' if same else '**no**'} |")
out.append("")

# ---- 3. atlas text
tmp = tempfile.mkdtemp()
for tag, src in (("old", "atlas"), ("new", GMD_ATLAS)):
    d = f"{tmp}/{tag}"; os.makedirs(d)
    for f in ("build_tex.py", "build_extra.py"): shutil.copy(f"atlas/{f}", d)
    for f in ("panel.csv", "global.csv", "meta.json", "stats.json", "sync.json"): shutil.copy(f"{src}/{f}", d)
    subprocess.run([sys.executable, "build_tex.py"], cwd=d, check=True, capture_output=True)
a, b = open(f"{tmp}/old/atlas.tex").read(), open(f"{tmp}/new/atlas.tex").read()
nums = len(re.findall(r"\d+\.\d+", a))
out += ["## 3. Atlas text", "", (f"`atlas.tex` rendered from the stored and the rerun files is **identical** ({len(a):,} characters, "
        f"{nums:,} decimal numbers). No value printed in the atlas changes.") if a == b else "`atlas.tex` **differs** between stored and rerun files.", ""]
shutil.rmtree(tmp)
out += ["## Verdict", "", ("No reported value and no p-value changes at the precision we report, except D10, which is itself the size "
        "of a floating-point rounding error.") if changed == [k for k in ro if k.startswith("D10")] and a == b and tot["p"] == 0
        else f"Changed at reported precision: {changed or 'none'}; atlas text {'identical' if a == b else 'differs'}; p-values changed: {tot['p']}."]
open(f"{DEST}/PRECISION.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
