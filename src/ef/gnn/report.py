"""G0 reports: the data card (gnn/G0_data_card.md), the missing-data report (gnn/G0_missing_data.md) and the full gap
tables (gnn/G0/*.csv.gz: every economy, parameter or edge, and year, with its gap class).

    python -m ef.gnn.report        # builds the dataset (ef.gnn.dataset) into build/gnn/g0, then writes the reports
"""
import argparse
import os

import numpy as np
import pandas as pd

from ef import config
from ef.data import validate
from ef.gnn import dataset as g

NAMES = validate.NAMES | {g.WORLD: 'World node'}


def node_gaps(n):
    """Long table: node, feature, year, gap class (feature cells that do not apply to a node are left out)."""
    C, nodes, feats, yrs = n['gap'], list(n['nodes']), list(n['features']), n['years']
    i, j, k = np.nonzero(C != 'not_a_feature')
    return pd.DataFrame({'node': np.array(nodes)[j], 'feature': np.array(feats)[k], 'year': yrs[i], 'gap': C[i, j, k]})


def coverage_table(G):
    """Per node and feature: years observed of 53, first and last observed year, and the missing years by class."""
    rows = []
    for (node, f), d in G.groupby(['node', 'feature'], sort=False):
        ok = d[d.gap == 'observed'].year
        miss = d[d.gap != 'observed']
        cls = '; '.join(f"{c} {_years(m.year)}" for c, m in miss.groupby('gap'))
        rows.append((node, f, len(ok), int(ok.min()) if len(ok) else None, int(ok.max()) if len(ok) else None, cls))
    return pd.DataFrame(rows, columns=['node', 'feature', 'observed', 'first', 'last', 'missing'])


def _years(ys):
    """'1970-1975, 1981' from a list of years."""
    ys = sorted(int(y) for y in ys); out = []; a = b = None
    for y in ys:
        if a is None: a = b = y
        elif y == b + 1: b = y
        else: out.append(f"{a}" if a == b else f"{a}–{b}"); a = b = y
    if a is not None: out.append(f"{a}" if a == b else f"{a}–{b}")
    return ', '.join(out)


def _md(df):
    cols = list(df.columns)
    return ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + \
        ["| " + " | ".join('' if (isinstance(v, float) and np.isnan(v)) or v is None else str(v) for v in r) + " |" for r in df.itertuples(index=False)]


def edge_year_table(E):
    """Per edge type and year: how many directed pairs fall in each gap class."""
    t = E.groupby(['year', 'gap']).size().unstack(fill_value=0)
    return t.reset_index()


def edge_node_table(E, isos):
    """Per economy: observed out- and in-edges of this type, of the possible, over 1970-2022."""
    rows = []
    for i in isos:
        o, n_ = E[E.src == i], E[E.dst == i]
        rows.append((NAMES.get(i, i), f"{(o.gap == 'observed').sum()} / {len(o)}" if len(o) else '—',
                     f"{(n_.gap == 'observed').sum()} / {len(n_)}" if len(n_) else '—',
                     _years(sorted(set(o[o.gap != 'observed'].year) | set(n_[n_.gap != 'observed'].year))) or '—'))
    return pd.DataFrame(rows, columns=['economy', 'observed out-edges', 'observed in-edges', 'years with any gap'])


def missing_report(r, n, E, G):
    isos = r['isos']; L = ["# G0 missing-data report — S31, 1970–2022", "",
        "Generated by `python -m ef.gnn.report` from `build/gnn/g0` (`src/ef/gnn/dataset.py`). Every gap is masked in the "
        "dataset and never filled. Full tables, one row per economy (or edge), parameter and year: `gnn/G0/*.csv.gz`.", "",
        "## Gap classes", "", "| Class | True zero or missing | Meaning |", "|---|---|---|"]
    L += [f"| `{k}` | {v[0]} | {v[1]} |" for k, v in g.GAP_CLASSES.items()]
    L += ["", "**Plain answer to \"true zero or missing\":** every node-feature gap is missing data (no node series has "
          "a structural zero). For trade, the IMF file records no zeros at all (0 of 138,217 rows), so no trade gap can be "
          "confirmed as a true zero: pairs with no recorded flow while both sides report other partners (`unrecorded`) "
          "are probable zeros, mostly South Africa's trade with Asian and Middle Eastern economies during the apartheid "
          "sanctions (1970–91) and China–South Korea before 1990, but they are masked like missing data. For bank claims "
          "no reported value is exactly zero; every gap is missing data. Oil exposure has no pinned source yet.", ""]
    # nodes
    cov = coverage_table(G); allc = G.gap.value_counts()
    L += ["## 1. Node features", "",
          f"{(G.gap == 'observed').sum():,} of {len(G):,} economy-feature-year cells are observed "
          f"({100 * (G.gap == 'observed').mean():.1f}%). Missing by class: " +
          ", ".join(f"{k} {v:,}" for k, v in allc.items() if k != 'observed') + ".", "",
          "The phase features are complete for every economy and year (past-only phases from Maddison, which is complete "
          "for 1950–2022). Russia's phases before 1991 rest on Maddison's back-cast Soviet-era estimates (method "
          "undocumented; `docs/data_validation.md`).", "",
          "### Coverage by feature (economies with every year observed, and the economies with gaps)", "",
          "| Feature | Complete economies | Economies with gaps (years observed of 53) |", "|---|---|---|"]
    for f in [f for f, _ in g.PHASE_FEATURES + g.ATLAS_FEATURES]:
        c = cov[(cov.feature == f) & (cov.node != g.WORLD)]
        full = (c.observed == 53).sum(); part = c[c.observed < 53].sort_values('observed')
        L.append(f"| {f} | {full} / {len(c)} | " + (", ".join(f"{NAMES.get(a, a)} {b}" for a, b in zip(part.node, part.observed)) or '—') + " |")
    L += ["", "### Every gap, by economy and feature", ""]
    gaps = cov[cov.observed < 53].copy(); gaps['node'] = gaps.node.map(lambda x: NAMES.get(x, x))
    L += _md(gaps[['node', 'feature', 'observed', 'first', 'last', 'missing']])
    # edges
    for k, title in (('trade', 'Trade edges (IMF IMTS, i → j goods exports)'), ('bank', 'Bank edges (BIS LBS, the fixed 10 lenders → borrowers, Q4 stocks)'),
                     ('oil', 'Oil edges (economy → world node)')):
        e = E[k]; vc = e.gap.value_counts()
        L += ["", f"## {2 + ['trade', 'bank', 'oil'].index(k)}. {title}", "",
              f"{len(e):,} directed pair-years; " + ", ".join(f"{a} {b:,}" for a, b in vc.items()) + ".", ""]
        if k == 'trade':
            L += [f"Of the observed pair-years, {int((e.exports_fob_usd.notna() & e.mirror_imports_cif_usd.isna()).sum()):,} have the "
                  f"exporter's figure only and {int((e.exports_fob_usd.isna() & e.mirror_imports_cif_usd.notna()).sum()):,} the "
                  f"partner's mirror only; neither is filled from the other. {int(e.exports_imf_estimate.sum()):,} exporter figures and "
                  f"{int(e.mirror_imf_estimate.sum()):,} mirror figures are IMF estimates (flagged). {int(e.proxy_reporting_unit.sum()):,} "
                  "pair-years use Belgium-Luxembourg (to 1996) or the South African Customs Union (to 1997) for Belgium and "
                  "South Africa (flagged). Russia's pairs before 1992 are `entity`: the USSR (code SUN) reported instead; its "
                  "trade is in the pinned file but is not used for Russia.", ""]
            u = e[e.gap.isin(['unrecorded', 'not_reporting'])].groupby(['src', 'dst', 'gap']).year.apply(_years).reset_index()
            L += ["Pairs with `unrecorded` or `not_reporting` years:", ""] + _md(u.rename(columns={'year': 'years'}))
        if k == 'bank':
            L += ["Lenders: France, Belgium, Sweden, Switzerland, Germany, Denmark, the Netherlands, the United States, the "
                  "United Kingdom and Japan (reporting since 1977-Q4; Sid's main set). No values before 1977 (`before_bis`). "
                  "Russia is a borrower only, from 1993-Q4 (claims on the USSR, BIS code SU, exist before and are not used). "
                  "The United States reports no claims on Iran in any year (`series_absent`). The United Kingdom has no 1982-Q4 "
                  "value for any borrower. Saudi Arabia's series start late for most lenders (to 2011).", ""]
            u = e[e.gap.isin(['series_gap', 'series_absent', 'not_yet'])].groupby(['src', 'dst', 'gap']).year.apply(_years).reset_index()
            L += ["Pairs with gaps after 1976:", ""] + _md(u.rename(columns={'year': 'years'}))
        if k == 'oil':
            L += ["Every economy has a link to the world node in every year. Its weight (net oil exports as a share of GDP) "
                  "is masked: no pinned source gives oil production and consumption by country (the pinned oil files are "
                  "prices and world consumption only). Adding one needs Sid's approval (CLAUDE.md).", ""]
        if k != 'oil':
            L += ["", "By year:", ""] + _md(edge_year_table(e))
            L += ["", "By economy:", ""] + _md(edge_node_table(e, isos))
    return "\n".join(L) + "\n"


