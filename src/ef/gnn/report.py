def main(argv=None):
    root = config.repo_root()
    ap = argparse.ArgumentParser(); ap.add_argument('--out', default=os.path.join(config.load()['paths']['build'], 'gnn', 'g0'))
    ap.add_argument('--atlas', default=os.path.join(config.load()['paths']['build'], 'data', 'atlas_s31')); a = ap.parse_args(argv)
    if not os.path.exists(os.path.join(a.atlas, 'panel.csv')): raise SystemExit("run make data first (build/data/atlas_s31)")
    r = g.build(a.out, a.atlas); n, E = g.load(a.out); G = node_gaps(n)
    d = os.path.join(root, 'gnn', 'G0'); os.makedirs(d, exist_ok=True)
    G.to_csv(os.path.join(d, 'node_gaps.csv.gz'), index=False, compression={'method': 'gzip', 'mtime': 0})
    coverage_table(G).to_csv(os.path.join(d, 'node_coverage.csv'), index=False)
    for k, e in E.items():
        e[['year', 'src', 'dst', 'gap'] + [c for c in e.columns if c.startswith('gap_')]].to_csv(
            os.path.join(d, f'edge_gaps_{k}.csv.gz'), index=False, compression={'method': 'gzip', 'mtime': 0})
    g.eia_comparison(r['isos'])[1].to_csv(os.path.join(d, 'eia_owid_comparison.csv'), index=False, float_format='%.6g')
    g.wb_vintage_comparison(r['isos']).to_csv(os.path.join(d, 'wb_vintage_comparison.csv.gz'), index=False,
                                              compression={'method': 'gzip', 'mtime': 0})
    open(os.path.join(root, 'gnn', 'G0_missing_data.md'), 'w').write(missing_report(r, n, E, G))
    open(os.path.join(root, 'gnn', 'G0_data_card.md'), 'w').write(data_card(r, n, E, G))
    print(f"wrote {a.out}, gnn/G0_data_card.md, gnn/G0_missing_data.md and gnn/G0/")


if __name__ == '__main__':
    main()
